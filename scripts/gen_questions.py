#!/usr/bin/env python3
"""Generates src/content/th/questions.ts from docs/03-question-bank.md (the source of truth).
Run: python3 scripts/gen_questions.py"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
md = (root / 'docs/03-question-bank.md').read_text(encoding='utf-8')
part = md.split('## 1. Personality Questions')[1].split('### ฉบับสั้น')[0]

dims, questions = [], []
dim = None
for block in re.split(r'\n(?=### D\d\d|#### Q\d\d)', part):
    m = re.match(r'### (D\d\d) — (.+)', block)
    if m:
        dim = m.group(1); dims.append({'id': dim, 'name': m.group(2).strip()}); continue
    m = re.match(r'#### (Q\d\d)( ⭐quick)?', block)
    if not m: continue
    qid, quick = m.group(1), bool(m.group(2))
    def field(name):
        f = re.search(r'^- \*\*' + re.escape(name) + r':\*\* (.+)$', block, re.M)
        return f.group(1).strip() if f else None
    opts = []
    for om in re.finditer(r'^  - `(q\d\d_[a-z_]+)` (.+)$', block, re.M):
        text = om.group(2).strip(); excl = '*(exclusive)*' in text
        opts.append({'id': om.group(1), 'text': text.replace('*(exclusive)*', '').strip(), **({'exclusive': True} if excl else {})})
    inline = field('Options')
    if inline and not opts:  # Q23: "(ชุดเดียวกับ Q22 แต่ id ต่างกัน) `q23_words` · ... · `q23_enough` text *(exclusive)*"
        prev = {o['id'].split('_', 1)[1]: o['text'] for o in questions[-1]['options']}
        for om in re.finditer(r'`(q\d\d_([a-z_]+))`([^`·]*)', inline):
            oid, suffix, rest = om.group(1), om.group(2), om.group(3)
            excl = '*(exclusive)*' in rest
            text = rest.replace('*(exclusive)*', '').strip() or prev.get(suffix, suffix)
            opts.append({'id': oid, 'text': text, **({'exclusive': True} if excl else {})})
    ms = int(re.match(r'\d+', field('maxSelect')).group(0))
    q = {'id': qid, 'dimension': dim, 'self': field('Self'), 'perceived': field('Perceived'),
         'options': opts, 'maxSelect': ms, 'freeText': True, 'quick': quick,
         'reflectionPrompt': (field('Reflection Prompt') or '').strip('"“”')}
    note = field('หมายเหตุ Safety')
    if note:
        nm = re.search(r'\*"(.+?)"\*', note); q['safetyNote'] = nm.group(1) if nm else note
    assert q['self'] and q['perceived'] and len(opts) >= 3, qid
    questions.append(q)

assert len(questions) == 36 and len(dims) == 12, (len(questions), len(dims))

# ---- Mirror questions M01–M07 (§2): table rows + "**Mxx** `id` text · ..." option lines ----
mpart = md.split('## 2. Mirror Questions')[1].split('## 3.')[0]
mirrors = []
for row in re.finditer(r'^\| (M\d\d) \| (D\d\d) \| ([^|]+) \| ([^|]+) \| (\d+) \|$', mpart, re.M):
    mid = row.group(1)
    block = re.search(r'^\*\*' + mid + r'\*\* (.+?)\n- Reflection Prompt: (.+?)$', mpart, re.M | re.S)
    assert block, mid
    opts = [{'id': om.group(1), 'text': om.group(2).strip()} for om in re.finditer(r'`(m\d\d_[a-z_]+)` ([^`·]+)', block.group(1))]
    assert len(opts) >= 3, mid
    mirrors.append({'id': mid, 'dimension': row.group(2), 'self': row.group(3).strip(), 'perceived': row.group(4).strip(),
                    'options': opts, 'maxSelect': int(row.group(5)), 'freeText': True,
                    'reflectionPrompt': block.group(2).strip().strip('"“”')})
assert [m['id'] for m in mirrors] == [f'M0{i}' for i in range(1, 8)], [m['id'] for m in mirrors]
out = root / 'src/content/th/questions.ts'
out.write_text(
    '// GENERATED by scripts/gen_questions.py from docs/03-question-bank.md — do not edit by hand.\n'
    "import type { QuestionContent } from '../types';\n\n"
    f'export const DIMENSIONS = {json.dumps(dims, ensure_ascii=False, indent=2)} as const;\n\n'
    f'export const QUESTIONS: QuestionContent[] = {json.dumps(questions, ensure_ascii=False, indent=2)};\n\n'
    '/** Mirror questions for Ch4 (docs/03 §2). */\n'
    f'export const MIRRORS: QuestionContent[] = {json.dumps(mirrors, ensure_ascii=False, indent=2)};\n',
    encoding='utf-8')
print(f'wrote {len(questions)} questions, {sum(q["quick"] for q in questions)} quick, {len(mirrors)} mirror questions')
